local function write_effective_include_all(target, platform_name, platform_layer, io_module)
    local headers = {}
    local project_dir = os.projectdir()

    local function add_layer(layer)
        local root = path.join(project_dir, layer)
        for _, header in ipairs(os.files(path.join(root, "mc/**.h"))) do
            local relative = path.relative(header, root):gsub("\\", "/")
            headers[relative] = true
        end
    end

    add_layer("src")
    add_layer(platform_layer)

    local relative_paths = table.keys(headers)
    table.sort(relative_paths)

    local output = path.join(target:autogendir(), "levilamina_header_include_all_" .. platform_name .. ".h")

    local lines = {
        "// Generated by xmake. Do not edit.",
        "#pragma once",
        "",
    }
    for _, relative in ipairs(relative_paths) do
        table.insert(lines, "#include \"" .. relative .. "\"")
    end
    table.insert(lines, "")
    io_module.writefile(output, table.concat(lines, "\n"))
end

local function configure_header_target(platform_name, platform_layer, platform_define)
    set_languages("c++20")
    set_symbols("debug")
    set_exceptions("none")
    add_headerfiles("src/(mc/**.h)", platform_layer .. "/(mc/**.h)")
    add_includedirs(platform_layer, "src")
    add_defines(platform_define)
    add_files("test/main.cpp")
    before_build(function (target)
        write_effective_include_all(target, platform_name, platform_layer, io)
    end)
end

local function add_autogen_include(target)
    target:add("includedirs", target:autogendir())
end

local function load_android_dependency_lock(json, expected_manifest_sha256)
    local lock_path = get_config("android_dependency_lock")
    if not lock_path or #lock_path == 0 then
        return nil, "Android builds require --android_dependency_lock=<generated-runtime-lock.json>"
    end
    lock_path = path.absolute(lock_path)
    if not os.isfile(lock_path) then
        return nil, "Android dependency runtime lock does not exist: " .. lock_path
    end

    local lock = json.loadfile(lock_path)
    if not lock or lock.schema_version ~= 1 then return nil, "Android dependency lock schema_version must be 1" end
    if lock.target ~= "aarch64-linux-android21" then return nil, "Android dependency lock target mismatch" end
    if lock.architecture ~= "arm64-v8a" then return nil, "Android dependency lock architecture mismatch" end
    if lock.api_level ~= 21 then return nil, "Android dependency lock API level mismatch" end
    if lock.ndk_revision ~= "28.2.13676358" then return nil, "Android dependency lock NDK revision mismatch" end
    if lock.manifest_sha256 ~= expected_manifest_sha256 then
        return nil, "Android dependency runtime lock was generated from a different manifest"
    end
    if get_config("arch") ~= "arm64-v8a" then return nil, "header_android requires -a arm64-v8a" end

    if type(lock.include_roots) ~= "table" or #lock.include_roots == 0 then
        return nil, "Android dependency lock contains no include roots"
    end
    for _, include_root in ipairs(lock.include_roots) do
        if not path.is_absolute(include_root) or not os.isdir(include_root) then
            return nil, "Android dependency include root does not exist: " .. tostring(include_root)
        end
    end
    for _, required_header in ipairs(lock.required_headers or {}) do
        if not path.is_absolute(required_header) or not os.isfile(required_header) then
            return nil, "Android dependency required header does not exist: " .. tostring(required_header)
        end
    end
    return lock
end

